"""Drafts a CV pool + fills the generic template from a user's own profile.yaml.

The bootstrap is the "onboarding" half of the tailored-CV feature (the other
half, cvgen/service.py's ensure_tailored_cv, only ever SELECTS from an
already-curated pool). Here the model genuinely authors the first draft's
text -- Alberto's own framing is "a first draft you edit" -- so every
generated bullet still goes through the same escape_latex/is_typesettable
guard real curated content is held to before it ever reaches a .yaml file,
and the written pool carries an explicit DRAFT header (see
bootstrap_cv_pool's DRAFT_HEADER) instead of any code-level lock on first use.
"""

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from moonlighter.application.cvgen.latex.compile import compile_pdf
from moonlighter.application.cvgen.latex.cv_template import base_fields, strip_marker_lines
from moonlighter.application.cvgen.latex.render import (
    MAXIMUM_BULLETS,
    MAXIMUM_OPEN_SOURCE,
    CVSelection,
    render_cv,
)
from moonlighter.application.cvgen.latex.template_fill import fill_template
from moonlighter.application.cvgen.paths import resolved_pool_path, resolved_template_dir
from moonlighter.application.cvgen.pool.bootstrap_error import BootstrapError
from moonlighter.application.cvgen.pool.draft import draft_pool
from moonlighter.application.cvgen.pool.loader import CVPool, PoolError, dump_pool, load_pool
from moonlighter.core.llm.caller import LLMCaller

DRAFT_HEADER = (
    "# DRAFT — review before using this for a real application\n"
    "# Generated by moonlighter's CV-pool bootstrap from your profile.yaml.\n"
    "# Read every bullet before your first real application uses it.\n\n"
)

DRAFT_TEX_NAME = "cv-draft.tex"


def _sample_selection(pool: CVPool, template: str) -> CVSelection:
    """A CVSelection covering the whole freshly drafted pool.

    The per-job engine builds this from one LLM call per posting; the
    bootstrap has no posting, so it stands in for the model with the widest
    honest selection -- every id in the pool, under the SAME one-page budget
    (render.py's MAXIMUM_BULLETS/MAXIMUM_OPEN_SOURCE) a real selection is held to,
    so the draft PDF looks like the documents this pool will actually
    produce rather than an everything-at-once version of it. Summary and
    expertise come from the template's own base declarations, which is
    precisely what a USE_BASE decision renders. No translations: the draft
    is English, per the spec's scope cut.
    """
    summary, expertise = base_fields(template)
    bullets = tuple(bullet.id for experience in pool.experiences for bullet in experience.bullets)[
        :MAXIMUM_BULLETS
    ]
    return CVSelection(
        language="en",
        summary=summary,
        technical_expertise=expertise,
        bullets=bullets,
        open_source=tuple(bullet.id for bullet in pool.open_source)[:MAXIMUM_OPEN_SOURCE],
        translations={},
    )


@dataclass(frozen=True)
class BootstrapOutcome:
    pool_path: Path
    template_path: Path
    pdf_path: Path | None
    bullet_count: int


async def bootstrap_cv_pool(
    profile: dict[str, Any], config: dict[str, Any], caller: LLMCaller, *, force: bool = False
) -> BootstrapOutcome:
    """Draft a CV pool + adapt the generic template from `profile`.

    Writes both to the config's (or default) paths -- the shared function both
    the MCP tool and the CLI subcommand call, so neither reimplements the
    other.
    """
    pool_path = resolved_pool_path(config)
    if pool_path.exists() and not force:
        raise BootstrapError(
            f"a CV pool already exists at {pool_path} — pass force=True to overwrite it"
        )
    pool = await draft_pool(profile, caller)
    pool_path.parent.mkdir(parents=True, exist_ok=True)

    # Write to a sibling temp file, validate THAT, and only rename into place
    # once validation passes -- never write-then-validate-in-place. Under
    # force=True the real pool_path may hold the operator's previous,
    # perfectly good pool; validating in place would mean the only recovery
    # from a bad draft is a pool file already overwritten with garbage. The
    # temp file never touches pool_path until it has already proven loadable,
    # so a failed draft leaves the previous pool (or no pool) exactly as it
    # was -- nothing for cv_bootstrap_offer or ensure_tailored_cv to trip on.
    tmp_path = pool_path.with_suffix(".yaml.tmp")
    tmp_path.write_text(DRAFT_HEADER + dump_pool(pool))
    try:
        load_pool(tmp_path)
    except PoolError as error:
        tmp_path.unlink(missing_ok=True)
        raise BootstrapError(
            f"the drafted pool is not loadable, so it was discarded: {error}"
        ) from error
    tmp_path.replace(pool_path)

    template_directory = resolved_template_dir(config)
    template_directory.mkdir(parents=True, exist_ok=True)
    template_path = template_directory / "cv-template.en.tex"
    filled = fill_template(profile)
    template_path.write_text(filled)

    # Compile a SAMPLE RENDER, never the template itself: the template still
    # carries the four per-job markers, and '%' is LaTeX's comment character,
    # so \cvlistitem{ + a marker opens a group whose closing brace is
    # swallowed as a comment -- pdflatex fails on EVERY machine, and a None
    # pdf_path then gets misread as "pdflatex is not installed." The sample
    # goes through render_cv, the same function the per-job path uses, so a
    # PDF here proves the pool AND the template are a working pair.
    draft_tex = template_directory / DRAFT_TEX_NAME
    draft_tex.write_text(
        strip_marker_lines(render_cv(filled, _sample_selection(pool, filled), pool))
    )
    pdf_path = compile_pdf(draft_tex)
    bullet_count = sum(len(experience.bullets) for experience in pool.experiences) + len(
        pool.open_source
    )
    return BootstrapOutcome(
        pool_path=pool_path,
        template_path=template_path,
        pdf_path=pdf_path,
        bullet_count=bullet_count,
    )
